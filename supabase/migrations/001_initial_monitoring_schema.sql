-- =============================================================================
-- Maintenance Function: Hourly Rollup & Retention Cleanup
-- =============================================================================
CREATE OR REPLACE FUNCTION public.rollup_and_cleanup_telemetry()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_raw_days int4 := 14;
  v_hourly_days int4 := 90;
BEGIN
  SELECT raw_retention_days, hourly_rollup_retention_days
    INTO v_raw_days, v_hourly_days
    FROM public.monitoring_settings
    WHERE id = 1;

  -- Upsert hourly rollups for recent metrics
  INSERT INTO public.system_metrics_hourly (
    device_id,
    hour_bucket,
    samples_count,
    cpu_avg_percent,
    cpu_max_percent,
    memory_available_min_bytes,
    swap_used_max_bytes,
    temperature_avg_celsius,
    temperature_max_celsius,
    root_disk_max_percent
  )
  SELECT
    device_id,
    date_trunc('hour', recorded_at) AS hour_bucket,
    count(*)::int4 AS samples_count,
    avg(cpu_percent)::float4,
    max(cpu_percent)::float4,
    min(memory_available_bytes)::int8,
    max(swap_used_bytes)::int8,
    avg(temperature_celsius)::float4,
    max(temperature_celsius)::float4,
    max(root_disk_percent)::float4
  FROM public.system_metrics
  WHERE recorded_at >= now() - interval '2 hours'
  GROUP BY device_id, date_trunc('hour', recorded_at)
  ON CONFLICT (device_id, hour_bucket) DO UPDATE SET
    samples_count = EXCLUDED.samples_count,
    cpu_avg_percent = EXCLUDED.cpu_avg_percent,
    cpu_max_percent = EXCLUDED.cpu_max_percent,
    memory_available_min_bytes = EXCLUDED.memory_available_min_bytes,
    swap_used_max_bytes = EXCLUDED.swap_used_max_bytes,
    temperature_avg_celsius = EXCLUDED.temperature_avg_celsius,
    temperature_max_celsius = EXCLUDED.temperature_max_celsius,
    root_disk_max_percent = EXCLUDED.root_disk_max_percent;

  -- Prune expired raw records
  DELETE FROM public.system_metrics
    WHERE recorded_at < now() - make_interval(days => COALESCE(v_raw_days, 14));
  DELETE FROM public.container_metrics
    WHERE recorded_at < now() - make_interval(days => COALESCE(v_raw_days, 14));
  DELETE FROM public.service_checks
    WHERE checked_at < now() - make_interval(days => COALESCE(v_raw_days, 14));
  DELETE FROM public.system_metrics_hourly
    WHERE hour_bucket < now() - make_interval(days => COALESCE(v_hourly_days, 90));
END;
$$;
